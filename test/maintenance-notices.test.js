'use strict';
const checks = require('./_checks');
const assert = require('node:assert/strict');
const fs = require('fs'), os = require('os'), path = require('path');
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'epilykos-maint-'));
process.chdir(dir); process.env.LOG_TO_FILE = 'false';
const database = require('../modules/database'); database.initializeDatabase();
const check = require('../modules/dbCheck');
const file = path.join(dir, 'test.db'), marker = path.join(dir, '.running'), result = path.join(dir, 'result.json');
check.setPathsForTests(file, marker, result);
(async () => {
  assert.equal(check.markStart(), false); assert.equal(check.markStart(), true);
  check.markCleanStop(); assert.equal(fs.existsSync(marker), false);
  const db = new (require('better-sqlite3'))(file); db.exec('CREATE TABLE data(value); INSERT INTO data VALUES(1)'); db.close();
  const a = check.run('test'); assert.strictEqual(check.run('concurrent'), a);
  const healthy = await a; assert.equal(healthy.ok, true); assert.equal(check.weeklyDue(), false);
  assert.equal(check.weeklyDue(Date.now() + check.WEEK_MS + 1000), true);
  fs.writeFileSync(file, 'this is a damaged database');
  const broken = await check.run('unclean shutdown'); assert.equal(broken.ok, false); assert.ok(broken.problems.length);
  assert.equal(check.last().reason, 'unclean shutdown'); assert.equal(check.busy(), false);
  const notices = require('../modules/notices');
  const now = Date.now();
  assert.equal(notices.backupState(now).due, false);
  database.setConfig('backup_reminder_started', String(now - notices.MONTH_MS - 1000));
  assert.equal(notices.backupState(now).due, true);
  database.setConfig('backup_downloaded_at', new Date(now).toISOString()); assert.equal(notices.backupState(now).due, false);
  database.setConfig('backup_downloaded_at', new Date(now - 31*86400000).toISOString());
  database.setConfig('backup_reminder_until', String(now + 7*86400000)); assert.equal(notices.backupState(now).due, false);
  process.env.EPILYKOS_CLOCK_FILE = path.join(dir, 'clock.json');
  fs.writeFileSync(process.env.EPILYKOS_CLOCK_FILE, JSON.stringify({synchronized:false}));
  let status = await notices.status(); assert.ok(status.notices.some(n => n.id === 'clock')); assert.ok(status.notices.some(n => n.id === 'database'));
  fs.writeFileSync(process.env.EPILYKOS_CLOCK_FILE, JSON.stringify({synchronized:true}));
  status = await notices.status(); assert.ok(!status.notices.some(n => n.id === 'clock'));
  fs.utimesSync(process.env.EPILYKOS_CLOCK_FILE, new Date(0), new Date(0));
  assert.ok((await notices.status()).notices.some(n => n.id === 'clock'));
  await check.stop(); database.getDb().close(); fs.rmSync(dir, {recursive:true, force:true});
  checks.done();
})().catch(e => { console.error(e); process.exitCode=1; });
