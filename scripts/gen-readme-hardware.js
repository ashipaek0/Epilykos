#!/usr/bin/env node
'use strict';
/*
 * Keeps the "Supported hardware" table in README.md in step with the profile files.
 *
 *   node scripts/gen-readme-hardware.js          rewrite the table in README.md
 *   node scripts/gen-readme-hardware.js --check  exit 1 if README.md is out of date (used by npm test)
 *
 * The table sits between <!-- hardware:start --> and <!-- hardware:end -->. Edit this script, not
 * the table. The wiki's Supported hardware page is generated from the same profile files.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const START = '<!-- hardware:start -->';
const END = '<!-- hardware:end -->';

// Protocol ids as written in the profile files, in the words the app's UI uses.
const PROTOCOLS = {
  'solarman-v5': 'WiFi dongle (Solarman V5)',
  'luxpower-tcp': 'WiFi dongle (LuxPower)',
  'felicity-tcp': 'WiFi dongle (Felicity TCP/JSON)',
  growatt: 'WiFi dongle (Growatt)',
  'ble-gatt': 'Bluetooth',
  'modbus-rtu': 'RS232 / RS485 serial (Modbus RTU)',
  'voltronic-qpigs': 'RS232 serial (Voltronic QPIGS)',
  'phocos-ascii': 'RS232 / RS485 serial (Phocos)',
  'solax-aa55': 'USB serial (SolaX AA55)',
  'vedirect-streaming': 'USB serial (VE.Direct)',
  jbd: 'UART / RS485 (JBD)',
  'jk-rs485': 'RS485 (JK)',
  'pace-v25': 'RS232 / RS485 (PACE protocol 25)',
};

function load(dir) {
  const full = path.join(ROOT, dir);
  return fs.readdirSync(full)
    .filter((f) => f.endsWith('.json'))
    .map((f) => ({ id: f.replace(/\.json$/, ''), ...JSON.parse(fs.readFileSync(path.join(full, f), 'utf8')) }))
    .filter((p) => p.placeholder !== true) // unverified skeletons the app hides from its lists
    .sort((a, b) => a.name.localeCompare(b.name));
}

const cell = (v) => String(v ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ').trim() || '';
const isBms = (p) => /bms/i.test(`${p.id} ${p.name}`);
const status = (p) => (p.status === 'unverified' ? 'Unverified' : '');
const via = (p) => PROTOCOLS[p.protocol ?? p.transport] ?? (p.connection === 'tcp' ? 'Modbus TCP' : 'RS485 (Modbus RTU)');

function table(head, rows) {
  return [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
}

function render() {
  const modbus = load('profiles').map((p) => ({ name: p.name, via: via(p), status: status(p) }));
  const dongles = load('profiles/dongles').map((p) => ({ name: p.name, via: via(p), status: status(p) }));
  const serial = load('profiles/rs232');
  const inverters = [...modbus, ...dongles, ...serial.filter((p) => !isBms(p)).map((p) => ({ name: p.name, via: via(p), status: status(p) }))]
    .sort((a, b) => a.name.localeCompare(b.name));
  const bms = serial.filter(isBms).map((p) => [p.name, via(p), status(p)]);
  const hasUnverified = [...inverters, ...bms.map((r) => ({ status: r[2] }))].some((r) => r.status);

  return [
    START,
    '<!-- Generated by scripts/gen-readme-hardware.js from the files in profiles/. Run `node scripts/gen-readme-hardware.js` after changing a profile. -->',
    '',
    '### Inverters and charge controllers',
    '',
    table(['Device', 'How it connects', 'Status'], inverters.map((r) => [r.name, r.via, r.status])),
    '',
    '### Wired battery BMS',
    '',
    table(['Device', 'How it connects', 'Status'], bms),
    '',
    'Bluetooth battery packs need no profile: scan for them and Epilykos labels any pack it recognises (JK, JBD, Daly, Seplos, ANT, Renogy, EG4, PACE and more). ' +
      'Anything you reach through Home Assistant, MQTT, Tuya or a REST API needs no profile either.',
    hasUnverified ? '\n**Unverified** profiles were written from the maker\'s register document and have not been tested on real hardware yet. If you have the device, a report of what works helps.' : '',
    '',
    'Details for each connection, including ports and serial settings, are on the wiki\'s **[Supported hardware](https://epilykos.ashipaek0.com.ng/data-sources/supported-hardware/)** page. To add your own inverter, see **[Add your inverter](https://epilykos.ashipaek0.com.ng/development/add-your-inverter/)**.',
    END,
  ].filter((l, i, a) => !(l === '' && a[i - 1] === '')).join('\n');
}

function apply(readme) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error(`README.md needs the ${START} and ${END} markers`);
  return readme.slice(0, a) + render() + readme.slice(b + END.length);
}

module.exports = { render, apply };

if (require.main === module) {
  const file = path.join(ROOT, 'README.md');
  const current = fs.readFileSync(file, 'utf8');
  const next = apply(current);
  if (process.argv.includes('--check')) {
    if (next !== current) { console.error('README.md hardware table is out of date. Run: node scripts/gen-readme-hardware.js'); process.exit(1); }
    console.log('README.md hardware table is up to date.');
  } else if (next !== current) { fs.writeFileSync(file, next); console.log('README.md hardware table updated.'); }
  else console.log('README.md hardware table already up to date.');
}
